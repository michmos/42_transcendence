// Vite plugin to extract types from database schema
import fs from 'node:fs';
import path from 'node:path';
import type { Plugin, ViteDevServer } from 'vite';

export function viteTypesExtractor(): Plugin {
  return {
    name: 'vite-types-extractor',
    configureServer(server: ViteDevServer) {
      // Watch for schema changes and regenerate types
      const schemaPath = path.resolve(
        process.cwd(),
        '../database/schema.prisma'
      );

      if (fs.existsSync(schemaPath)) {
        fs.watchFile(schemaPath, () => {
          console.log('📊 Database schema changed, refreshing types...');
          server.ws.send({
            type: 'full-reload',
            path: '*',
          });
        });
      }
    },
    async buildStart() {
      // Extract types from Prisma schema at build time
      this.emitFile({
        type: 'asset',
        fileName: 'types/database.d.ts',
        source: await generateTypesFromSchema(),
      });
    },
    transform(code: string, id: string) {
      // Inject virtual module for database types
      if (id === 'virtual:db-types') {
        return `
          // Virtual module with database types
          ${generateTypesFromSchema()}
          
          // Export for use in application
          export * from './types';
        `;
      }
    },
    resolveId(id: string) {
      if (id === 'virtual:db-types') {
        return id;
      }
    },
  };
}

async function generateTypesFromSchema(): Promise<string> {
  try {
    // Dynamic import to safely extract types without Node.js runtime
    const dbPath = path.resolve(process.cwd(), '../database');
    const schemaPath = path.join(dbPath, 'schema.prisma');

    if (!fs.existsSync(schemaPath)) {
      console.warn('⚠️ Prisma schema not found, using fallback types');
      return getFallbackTypes();
    }

    // Read Prisma schema file
    const schemaContent = fs.readFileSync(schemaPath, 'utf-8');

    // Extract types from Prisma schema
    const extractedTypes = extractTypesFromPrismaSchema(schemaContent);

    console.log('✅ Successfully extracted types from database schema');
    return extractedTypes;
  } catch (error) {
    console.error('❌ Error extracting types from database:', error);
    return getFallbackTypes();
  }
}

function extractTypesFromPrismaSchema(schemaContent: string): string {
  const models: string[] = [];
  const enums: string[] = [];

  // Extract model definitions
  const modelRegex = /model\s+(\w+)\s*{([^}]+)}/g;
  let modelMatch;

  while ((modelMatch = modelRegex.exec(schemaContent)) !== null) {
    const [, modelName, modelBody] = modelMatch;
    if (modelName && modelBody) {
      const interfaceFields = extractFieldsFromModel(modelBody);

      models.push(`
export interface ${modelName} {
${interfaceFields}
}`);
    }
  }

  // Extract enum definitions
  const enumRegex = /enum\s+(\w+)\s*{([^}]+)}/g;
  let enumMatch;

  while ((enumMatch = enumRegex.exec(schemaContent)) !== null) {
    const [, enumName, enumBody] = enumMatch;
    if (enumName && enumBody) {
      const enumValues = extractEnumValues(enumBody);

      enums.push(`
export enum ${enumName} {
${enumValues}
}`);
    }
  }

  // Generate API types dynamically from discovered models
  const apiTypes = generateApiTypesFromModels(models);

  return `
// Auto-generated types from Prisma schema
// Do not edit manually - this file is generated by vite-types-extractor

${models.join('\n')}

${enums.join('\n')}

${apiTypes}
`;
}

function extractFieldsFromModel(modelBody: string): string {
  const fields: string[] = [];
  const lines = modelBody.split('\n');

  for (const line of lines) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('//') || trimmed.startsWith('@@')) {
      continue;
    }

    // Parse field definition: fieldName Type @attributes
    const fieldMatch = trimmed.match(/(\w+)\s+(\w+)(\?)?/);
    if (fieldMatch) {
      const [, fieldName, fieldType, optional] = fieldMatch;
      if (fieldName && fieldType) {
        const tsType = mapPrismaTypeToTypeScript(fieldType);
        const optionalMarker = optional ? '?' : '';

        fields.push(`  ${fieldName}${optionalMarker}: ${tsType};`);
      }
    }
  }

  return fields.join('\n');
}

function generateApiTypesFromModels(models: string[]): string {
  try {
    // Scan API endpoints to generate request/response types
    const apiPath = path.resolve(process.cwd(), '../api/src/api');
    const apiTypes = scanApiEndpoints(apiPath, models);

    return `
// Auto-generated API types from API endpoints
${apiTypes}

// Generic API Response wrapper
export interface ApiResponse<T = unknown> {
  success: boolean;
  data?: T;
  error?: string;
}`;
  } catch {
    console.warn('⚠️ Could not scan API endpoints, using minimal types');
    return `
// Minimal API types (API scanning failed)
export interface ApiResponse<T = unknown> {
  success: boolean;
  data?: T;
  error?: string;
}`;
  }
}

function scanApiEndpoints(apiPath: string, models: string[]): string {
  const requestTypes: string[] = [];
  const responseTypes: string[] = [];

  try {
    if (!fs.existsSync(apiPath)) {
      return generateDefaultApiTypes(models);
    }

    // Scan API directory for endpoint files
    const apiFiles = fs
      .readdirSync(apiPath, { recursive: true })
      .filter(
        (file): file is string =>
          typeof file === 'string' && file.endsWith('.ts')
      )
      .map((file) => path.join(apiPath, file));

    for (const filePath of apiFiles) {
      const content = fs.readFileSync(filePath, 'utf-8');
      const endpointTypes = extractEndpointTypes(content, filePath);

      requestTypes.push(...endpointTypes.requests);
      responseTypes.push(...endpointTypes.responses);
    }

    return `
${requestTypes.join('\n')}

${responseTypes.join('\n')}`;
  } catch (error) {
    console.warn('⚠️ Error scanning API endpoints:', error);
    return generateDefaultApiTypes(models);
  }
}

function extractEndpointTypes(
  content: string,
  filePath: string
): {
  requests: string[];
  responses: string[];
} {
  const requests: string[] = [];
  const responses: string[] = [];

  // Extract model name from file path (e.g., '/user/index.ts' -> 'User')
  const modelName = path.basename(path.dirname(filePath));
  const capitalizedModel =
    modelName.charAt(0).toUpperCase() + modelName.slice(1);

  // Look for HTTP method handlers and extract their schemas
  const methodRegex = /(POST|PUT|PATCH|DELETE)\s*['"`]([^'"`]+)['"`]/g;
  let methodMatch;

  while ((methodMatch = methodRegex.exec(content)) !== null) {
    const [, method] = methodMatch;

    switch (method) {
      case 'POST':
        // Generate create request type
        requests.push(`
export interface Create${capitalizedModel}Request {
  // Auto-generated from ${path.relative(process.cwd(), filePath)}
  [key: string]: unknown;
}`);
        responses.push(
          `export type Create${capitalizedModel}Response = ApiResponse<${capitalizedModel}>;`
        );
        break;

      case 'PUT':
      case 'PATCH':
        // Generate update request type
        requests.push(`
export interface Update${capitalizedModel}Request {
  // Auto-generated from ${path.relative(process.cwd(), filePath)}
  [key: string]: unknown;
}`);
        responses.push(
          `export type Update${capitalizedModel}Response = ApiResponse<${capitalizedModel}>;`
        );
        break;

      case 'DELETE':
        // Generate delete request type
        requests.push(`
export interface Delete${capitalizedModel}Request {
  // Auto-generated from ${path.relative(process.cwd(), filePath)}
  uuid: string;
}`);
        responses.push(
          `export type Delete${capitalizedModel}Response = ApiResponse<{ deleted: boolean }>;`
        );
        break;
    }
  }

  // Add GET response type if this appears to be a REST endpoint
  if (content.includes('GET') || content.includes('fastify.get')) {
    responses.push(
      `export type Get${capitalizedModel}sResponse = ApiResponse<${capitalizedModel}[]>;`
    );
    responses.push(
      `export type Get${capitalizedModel}Response = ApiResponse<${capitalizedModel}>;`
    );
  }

  return { requests, responses };
}

function generateDefaultApiTypes(models: string[]): string {
  // Extract model names from interface definitions
  const modelNames = models
    .map((model) => {
      const match = model.match(/export interface (\w+)/);
      return match ? match[1] : null;
    })
    .filter(Boolean);

  const apiTypes: string[] = [];

  for (const modelName of modelNames) {
    apiTypes.push(`
// Auto-generated API types for ${modelName}
export interface Create${modelName}Request {
  [key: string]: unknown;
}

export interface Update${modelName}Request {
  [key: string]: unknown;
}

export interface Delete${modelName}Request {
  uuid: string;
}

export type Get${modelName}sResponse = ApiResponse<${modelName}[]>;
export type Get${modelName}Response = ApiResponse<${modelName}>;
export type Create${modelName}Response = ApiResponse<${modelName}>;
export type Update${modelName}Response = ApiResponse<${modelName}>;
export type Delete${modelName}Response = ApiResponse<{ deleted: boolean }>;`);
  }

  return apiTypes.join('\n');
}

function extractEnumValues(enumBody: string): string {
  const values: string[] = [];
  const lines = enumBody.split('\n');

  for (const line of lines) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('//')) {
      continue;
    }

    const valueMatch = trimmed.match(/(\w+)/);
    if (valueMatch) {
      const [, valueName] = valueMatch;
      values.push(`  ${valueName} = '${valueName}',`);
    }
  }

  return values.join('\n');
}

function mapPrismaTypeToTypeScript(prismaType: string): string {
  const typeMap: Record<string, string> = {
    String: 'string',
    Int: 'number',
    BigInt: 'bigint',
    Float: 'number',
    Decimal: 'number',
    Boolean: 'boolean',
    DateTime: 'string', // ISO string format
    Json: 'unknown',
    Bytes: 'Buffer',
  };

  return typeMap[prismaType] || prismaType;
}

function getFallbackTypes(): string {
  return `
// Fallback types when schema extraction fails

export interface User {
  uuid: string;
  email: string;
  createdAt?: string;
  updatedAt?: string;
}

export interface CreateUserRequest {
  email: string;
}

export interface DeleteUserRequest {
  uuid: string;
}

export interface ApiResponse<T = unknown> {
  success: boolean;
  data?: T;
  error?: string;
}

export type GetUsersResponse = ApiResponse<User[]>;
export type CreateUserResponse = ApiResponse<User>;
export type DeleteUserResponse = ApiResponse<{ deleted: boolean }>;
`;
}
